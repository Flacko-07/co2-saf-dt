"""
blend_datasets.py
Merge original (real) plant data with synthetic plant runs from the physics model.
"""
import pandas as pd
from config import DATA_DIR, PROC_DIR

# Paths (defined in config.py)
REAL_CSV  = DATA_DIR / "original_plant_runs.csv"      # your pilot data (≥1 row)
SYNTH_CSV = PROC_DIR / "synthetic_plant_runs.csv"      # generated by generate_synthetic_runs.py
BLEND_CSV = DATA_DIR / "blended_plant_runs.csv"        # output

def main():
    # 1. Load both datasets
    real  = pd.read_csv(REAL_CSV)
    synth = pd.read_csv(SYNTH_CSV)

    print(f"Real runs:   {len(real)} rows")
    print(f"Synthetic runs: {len(synth)} rows")

    # 2. Ensure column alignment (both must have the same columns)
    if set(real.columns) != set(synth.columns):
        missing_in_real = set(synth.columns) - set(real.columns)
        missing_in_synth = set(real.columns) - set(synth.columns)
        if missing_in_real:
            print(f"Warning: columns missing in real data: {missing_in_real}, will fill with NaN")
            for c in missing_in_real:
                real[c] = float('nan')
        if missing_in_synth:
            print(f"Warning: columns missing in synthetic data: {missing_in_synth}, will fill with NaN")
            for c in missing_in_synth:
                synth[c] = float('nan')
        # align column order
        common_cols = list(real.columns)
        real  = real[common_cols]
        synth = synth[common_cols]

    # 3. Concatenate (real first, then synthetic)
    blended = pd.concat([real, synth], ignore_index=True)

    # 4. Save
    blended.to_csv(BLEND_CSV, index=False)
    print(f"Blended dataset saved to {BLEND_CSV} ({len(blended)} rows)")

if __name__ == "__main__":
    main()